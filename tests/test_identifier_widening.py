"""Tests for the widened identifier terminals (PREDICATE/CONSTANT/NAME/
VARIABLE/SORT, generated by ``fol/_identifiers.py`` — see that module's
docstring for the design this pins down).

Every expected AST below is hand-computed from the grammar's own rules
(first-character case decides PREDICATE vs. term-valued; a bare NAME token
becomes a ``Constant``; ``const_``/bare-NAME both keep the matched text
verbatim, including any ``c_`` prefix — nothing here is generated from a
loop over the same code under test.

D10 (backward compatibility) is additionally verified OUTSIDE this file, by
a differential run of the FOLIO corpus (``tests/fixtures/folio_fol_strings.
txt``) against the parser as committed at HEAD before this widening: all
1214 lines that already parsed produced byte-identical ``repr()`` ASTs
under the widened grammar, and exactly 46 more lines newly parse — see
CHANGELOG.md's entry for this change. ``TestRegressionD10`` below re-checks
a hand-picked slice of that same guarantee in-suite.
"""

import unicodedata

import pytest

from unicode_fol_kit.fol.msflparser import MSFLParser
from unicode_fol_kit.fol.naming import NamingError, ParsingError
from unicode_fol_kit.fol._fol_nodes import (
    Atom, Variable, Constant, Number, Function, Measure,
    And, Or, Not, Implies, Quantifier,
)
from unicode_fol_kit.fol._msfl_nodes import (
    SortedQuantifier, SortedConstant, Lambda, LambdaVar, Application,
)
from unicode_fol_kit.fol._modal_nodes import Box
from unicode_fol_kit.fol._so_nodes import SecondOrderQuantifier
from unicode_fol_kit.fol import _identifiers

FOL = MSFLParser()


# ---------------------------------------------------------------------------
# Unicode letters — NFC and NFD
# ---------------------------------------------------------------------------

class TestUnicodeLetters:
    def test_nfc_polish_name_parses_as_constant(self):
        """'świątek' as given (NFC, the form almost every editor produces)."""
        text = "LostTo(x, świątek)"
        result = FOL.parse(text)
        assert result == Atom("LostTo", [Variable("x"), Constant("świątek")])

    def test_nfd_polish_name_parses_as_constant(self):
        """The SAME word, NFD-decomposed (ś -> 's' + U+0301 COMBINING ACUTE
        ACCENT, ą -> 'a' + U+0328 COMBINING OGONEK): the combining-mark
        continuation class (see _identifiers.combining_class) is what keeps
        this one identifier instead of a letter followed by a stray mark
        that derails the lexer."""
        nfd_name = unicodedata.normalize("NFD", "świątek")
        assert nfd_name != "świątek", "test is meaningless if NFD == NFC here"
        result = FOL.parse(f"LostTo(x, {nfd_name})")
        # The parsed Constant carries the exact source spelling, uncoerced to
        # any particular normal form — the grammar does not normalise.
        assert result == Atom("LostTo", [Variable("x"), Constant(nfd_name)])


# ---------------------------------------------------------------------------
# Underscore
# ---------------------------------------------------------------------------

class TestUnderscore:
    def test_underscored_constants_parse(self):
        result = FOL.parse("Sibling(dani_Shapiro, family_History)")
        assert result == Atom(
            "Sibling", [Constant("dani_Shapiro"), Constant("family_History")])

    def test_leading_underscore_is_still_rejected(self):
        """The underscore is a CONTINUATION character (position 2+), never
        the first — '_foo' opens with a character no identifier terminal
        accepts as its first."""
        with pytest.raises(NamingError):
            FOL.parse("P(_foo)")

    def test_underscored_predicate_parses(self):
        """PREDICATE carries the underscore too. 0.23.0 shipped this
        asymmetric — underscore in term position only — and that broke
        chem/interop.py, whose kit spelling of a ChemLog predicate capitalises
        only the first character: 17 of the chemical signature's 40 predicates
        spell as Has_bond_to / In_ring_of_size_6 / Net_charge_neutral, i.e. as
        names the kit's own parser refused. See
        test_chem_signature_kit_spellings_parse for the exhaustive check."""
        assert FOL.parse("Family_History(x)") == Atom(
            "Family_History", [Variable("x")])

    def test_leading_underscore_in_predicate_position_is_still_rejected(self):
        """The underscore stays a CONTINUATION character in predicate position
        too: it may not open the token, or the first character would no longer
        carry the predicate/term distinction."""
        with pytest.raises((NamingError, ParsingError)):
            FOL.parse("_Family(x)")


