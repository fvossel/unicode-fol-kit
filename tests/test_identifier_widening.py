# D6 — CONSTANT keeps its priority over the now-overlapping NAME
# ---------------------------------------------------------------------------

class TestConstantPriorityOverName:
    """Before this change, CONSTANT ('c_...'/Greek) and NAME never matched
    the same span: NAME never accepted an underscore. Widening NAME to
    accept '_' makes 'c_alpha' ALSO a full match for NAME's alpha-leading
    form (c -> [lowercase], _alpha -> legal NAME continuation with a second
    letter further on). CONSTANT.3 must still win over NAME.2 — this is the
    single most dangerous seam of the whole change (see fol/_identifiers.py's
    module docstring), so it is checked at the LEXER level (which terminal
    actually matched), not just via the resulting AST — the two terminals'
    transforms happen to produce the identical Constant either way (neither
    strips the 'c_' prefix), so an AST-only check could not tell them apart.
    """

    def test_c_prefixed_ascii_constant_lexes_as_constant(self):
        tokens = list(FOL.parser.lex("c_alpha"))
        assert [t.type for t in tokens] == ["CONSTANT"]

    def test_c_prefixed_ascii_constant_parses_to_the_verbatim_name(self):
        assert FOL.parse("P(c_alpha)") == Atom("P", [Constant("c_alpha")])

    def test_c_prefixed_unicode_constant_lexes_as_constant(self):
        """(D6) 'the c_ form itself may also carry Unicode letters'."""
        tokens = list(FOL.parser.lex("c_świątek"))
        assert [t.type for t in tokens] == ["CONSTANT"]

    def test_c_prefixed_unicode_constant_parses(self):
        assert FOL.parse("P(c_świątek)") == Atom("P", [Constant("c_świątek")])


