class TestDigitLeading:
    def test_digit_leading_identifier_parses_as_constant(self):
        result = FOL.parse("Hosted(beijing, 2008SummerOlympics)")
        assert result == Atom(
            "Hosted", [Constant("beijing"), Constant("2008SummerOlympics")])

    def test_digit_leading_identifier_as_a_function_head(self):
        """Digit-leading is folded into NAME, which — like any NAME — can
        also head a function application, never an atom (PREDICATE alone
        can do that, and PREDICATE never starts with a digit)."""
        result = FOL.parse("P(2008SummerOlympics(x))")
        assert result == Atom(
            "P", [Function("2008SummerOlympics", [Variable("x")])])

    def test_plain_integer_is_still_a_number(self):
        assert FOL.parse("P(2008)") == Atom("P", [Number(2008)])

    def test_decimal_is_still_a_number(self):
        assert FOL.parse("P(2.5)") == Atom("P", [Number(2.5)])


