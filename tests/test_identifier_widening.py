# D10 — a hand-picked slice of "every string 0.22.0 accepted still parses to
# the structurally identical AST". The full corpus-level guarantee (1214/1214
# FOLIO lines byte-identical, 46 newly accepted) was checked externally by
# diffing this working tree's parser against the parser committed at HEAD
# before this change, over every FOLIO line — see this file's module
# docstring and CHANGELOG.md.
# ---------------------------------------------------------------------------

class TestRegressionD10:
    def test_plain_ascii_atom(self):
        assert FOL.parse("Human(socrates)") == Atom("Human", [Constant("socrates")])

    def test_conjunction_and_implication(self):
        result = FOL.parse("∀x (Human(x) → Mortal(x)) ∧ Loves(alice, bob)")
        assert result == And(
            Quantifier("∀", Variable("x"), Implies(
                Atom("Human", [Variable("x")]), Atom("Mortal", [Variable("x")]))),
            Atom("Loves", [Constant("alice"), Constant("bob")]),
        )

    def test_negation_and_disjunction(self):
        result = FOL.parse("¬P(x) ∨ Q(x)")
        assert result == Or(Not(Atom("P", [Variable("x")])), Atom("Q", [Variable("x")]))

    def test_function_application(self):
        result = FOL.parse("P(dist(x, y))")
        assert result == Atom("P", [Function("dist", [Variable("x"), Variable("y")])])

    def test_c_form_constant_unchanged(self):
        assert FOL.parse("P(c_alpha)") == Atom("P", [Constant("c_alpha")])

    def test_single_letter_variable_unchanged(self):
        assert FOL.parse("P(x)") == Atom("P", [Variable("x")])

    def test_variable_with_digit_tail_unchanged(self):
        assert FOL.parse("P(x1)") == Atom("P", [Variable("x1")])

    def test_multiletter_ascii_constant_unchanged(self):
        assert FOL.parse("P(socrates)") == Atom("P", [Constant("socrates")])

    def test_arithmetic_comparison_unchanged(self):
        result = FOL.parse("dist(x, y) > z ∧ a1 = b1")
        assert isinstance(result, And)

    def test_lambda_application_unchanged(self):
        result = FOL.parse("(λx. P(x))(a)")
        assert result == Application(
            Lambda(LambdaVar("x"), Atom("P", [LambdaVar("x")])), Variable("a"))

    def test_previously_invalid_digit_leading_argument_now_rejected_case_stays_rejected(self):
        """'1' alone followed by something that is not a legal continuation
        character (no letter after it) is still not a number and not an
        identifier — only 'digits THEN a letter' became legal, not 'digits
        then anything'."""
        with pytest.raises((NamingError, ParsingError)):
            FOL.parse("P(1@)")


