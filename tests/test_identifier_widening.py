class TestClassification:
    def test_uppercase_first_is_a_predicate(self):
        assert FOL.parse("Ś(x)") == Atom("Ś", [Variable("x")])

    def test_single_lowercase_letter_is_a_variable(self):
        assert FOL.parse("P(ś)") == Atom("P", [Variable("ś")])

    def test_two_lowercase_letters_is_a_name_and_becomes_a_constant(self):
        assert FOL.parse("P(śa)") == Atom("P", [Constant("śa")])

    def test_caseless_script_identifier_is_term_valued(self):
        """Chinese has no upper/lower distinction, so str.isupper() is False
        for every character in it — every bare identifier from such a
        script is therefore term-valued (NAME, here two caseless letters),
        never eligible to head an atom on its own."""
        assert FOL.parse("P(中文)") == Atom("P", [Constant("中文")])

    def test_digit_leading_classifies_as_constant_not_number(self):
        assert FOL.parse("P(2008SummerOlympics)") == Atom(
            "P", [Constant("2008SummerOlympics")])

    def test_plain_digits_classify_as_number(self):
        assert FOL.parse("P(2008)") == Atom("P", [Number(2008)])

    def test_decimal_digits_classify_as_number(self):
        assert FOL.parse("P(2.5)") == Atom("P", [Number(2.5)])


