# Regression: the ``fol._identifiers`` lookahead rewrite (splicing small
# fixed-size lookahead atoms into the terminal patterns instead of repeating
# the full ``upper``/``lower`` class bodies at every continuation position,
# to shrink ``terminal_block`` from ~190KB to ~58KB) must not change the
# accepted language — see that module's "differently-spelled pattern for the
# exact same set of strings, never a different one" promise. Two ways it
# quietly did, both caught by an exhaustive per-codepoint scan rather than
# the corpus tests above (the FOLIO corpus and the rest of this file's
# formulas never happen to use these codepoints):
# ---------------------------------------------------------------------------

class TestRegressionLookaheadCeiling:
    """(D-CEILING) ``_letter_atom()``'s ``\\w``-based branch has no ceiling
    of its own — unlike the fully-enumerated ``upper``/``lower`` classes it
    replaces, which never scan past ``_identifiers._MAX_CODEPOINT``
    (0x2FFFF) — so without an explicit ceiling it silently accepted letters
    those classes never could, e.g. CJK Unified Ideograph Extension G
    (U+30000-U+3134A, ``str.isalpha()`` true)."""

    def test_codepoint_past_the_scan_ceiling_is_still_rejected(self):
        ext_g = chr(0x30000)
        assert ext_g.isalpha()  # sanity: genuinely a letter, just past the ceiling
        with pytest.raises(NamingError):
            FOL.parse(f"Q({ext_g})")

    def test_predicate_continuation_past_the_scan_ceiling_is_still_rejected(self):
        ext_g = chr(0x30000)
        with pytest.raises(NamingError):
            FOL.parse(f"A{ext_g}(x)")

    def test_sort_continuation_past_the_scan_ceiling_is_still_rejected(self):
        ext_g = chr(0x30000)
        MS = MSFLParser(many_sorted=True)
        with pytest.raises(NamingError):
            MS.parse(f"∀x :A{ext_g} (P(x))")


class TestRegressionUpperNonalphaContinuation:
    """(D-UPPER-NONALPHA) A continuation position (PREDICATE/SORT/NAME's
    own — position two onward) used to accept ANY codepoint with
    ``str.isupper() == True``, via a literal splice of ``uppercase_class()``
    (built from ``str.isupper()`` alone, no ``isalpha()`` condition). The
    lookahead rewrite's ``\\w``-based LETTER atom instead requires
    ``str.isalpha()``, which is not implied by ``str.isupper()``: Roman
    numerals (U+2160-U+216F, category Nl) and circled/squared Latin
    capitals (e.g. U+24B6, category So) are ``isupper() == True`` and
    ``isalpha() == False``, so they silently stopped being legal
    continuation characters. Fixed by giving LETTER an explicit
    ``upper_nonalpha`` alternative for exactly this sliver."""

    def test_circled_latin_capital_in_predicate_continuation(self):
        circled_a = "Ⓐ"  # CIRCLED LATIN CAPITAL LETTER A
        result = FOL.parse(f"A{circled_a}(x)")
        assert result == Atom(f"A{circled_a}", [Variable("x")])

    def test_roman_numeral_in_name_continuation(self):
        roman_one = "Ⅰ"  # ROMAN NUMERAL ONE
        result = FOL.parse(f"Q(a{roman_one})")
        assert result == Atom("Q", [Constant(f"a{roman_one}")])

    def test_circled_latin_capital_in_sort_continuation(self):
        circled_a = "Ⓐ"
        MS = MSFLParser(many_sorted=True)
        result = MS.parse(f"∀x :A{circled_a} (P(x))")
        assert result == SortedQuantifier(
            "∀", Variable("x"), f"A{circled_a}", Atom("P", [Variable("x")]))


