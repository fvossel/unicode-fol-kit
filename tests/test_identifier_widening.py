class TestGreekAndOperatorGlyphsUnaffected:
    def test_lambda_still_opens_a_lambda_term(self):
        result = FOL.parse("λx. P(x)")
        assert result == Lambda(LambdaVar("x"), Atom("P", [LambdaVar("x")]))

    def test_mu_still_opens_a_measure_term(self):
        result = FOL.parse("μ(a, b) > μ(c, d)")
        assert result == Atom(">", [
            Measure(Variable("a"), Variable("b")),
            Measure(Variable("c"), Variable("d")),
        ])

    def test_lowercase_greek_alpha_is_still_a_constant_via_the_greek_form(self):
        assert FOL.parse("P(α)") == Atom("P", [Constant("α")])

    def test_lowercase_greek_beta_is_still_a_constant_via_the_greek_form(self):
        assert FOL.parse("P(β)") == Atom("P", [Constant("β")])

    def test_lambda_and_mu_are_excluded_from_the_generated_letter_classes(self):
        assert "λ" not in _identifiers.lowercase_class()
        assert "μ" not in _identifiers.lowercase_class()
        assert "λ" not in _identifiers.uppercase_class()
        assert "μ" not in _identifiers.uppercase_class()

    def test_the_constant_greek_run_is_excluded_from_the_generated_letter_classes(self):
        for ch in "αβγδεζηθικνξοπρστυφχψω":
            assert ch not in _identifiers.lowercase_class(), ch
            assert ch not in _identifiers.uppercase_class(), ch

    def test_lambda_lexes_as_lambda_not_as_an_identifier(self):
        assert [t.type for t in FOL.parser.lex("λ")] == ["LAMBDA"]

    def test_greek_alpha_lexes_as_constant_not_as_a_predicate_or_name(self):
        assert [t.type for t in FOL.parser.lex("α")] == ["CONSTANT"]


