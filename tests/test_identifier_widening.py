class TestAcrossModes:
    def test_fol_mode(self):
        assert FOL.parse("LostTo(x, świątek)") == Atom(
            "LostTo", [Variable("x"), Constant("świątek")])

    def test_msfol_mode_including_sort(self):
        msfol = MSFLParser(many_sorted=True)
        result = msfol.parse("∀x :Person (P(x) → Q(świątek:Person))")
        assert isinstance(result, SortedQuantifier)
        assert result.variable == Variable("x")
        assert result.sort == "Person"
        assert result.formula == Implies(
            Atom("P", [Variable("x")]),
            Atom("Q", [SortedConstant("świątek", "Person")]),
        )

    def test_msfol_mode_sort_terminal_itself_widens(self):
        """SORT (':' + PREDICATE-shaped name) is unaffected by the
        letter-widening in this particular case (sort names are plain ASCII
        in the corpus), but the underscored/digit-leading CONSTANT it
        annotates must still carry through."""
        msfol = MSFLParser(many_sorted=True)
        result = msfol.parse("P(family_History:Person)")
        assert result == Atom("P", [SortedConstant("family_History", "Person")])

    def test_msfl_mode(self):
        msfl = MSFLParser(many_sorted=True, fuzzy=True)
        result = msfl.parse("P(family_History:Person)")
        assert result == Atom("P", [SortedConstant("family_History", "Person")])

    def test_modal_mode(self):
        modal = MSFLParser(modal=True)
        result = modal.parse("□P(świątek)")
        assert result == Box(Atom("P", [Constant("świątek")]))

    def test_second_order_mode(self):
        so = MSFLParser(second_order=True)
        result = so.parse("∃P (P(świątek))")
        assert result == SecondOrderQuantifier(
            "∃", "P", 1, Atom("P", [Constant("świątek")]))


